  <h1>Política de privacidad</h1>
  <p>De conformidad con el Reglamento (UE) 2016/679 (RGPD) y la Ley Orgánica 3/2018 (LOPDGDD), se informa a los usuarios sobre el tratamiento de sus datos personales.</p>

  <h2>1. Responsable del tratamiento</h2>
  <p>Inpronet Solutions S.L. — Correo de contacto: info@scrapenvases.com</p>

  <h2>2. Finalidad</h2>
  <p>Los datos que nos facilites a través del formulario de la Oficina Técnica de SCRAPs (OTS) se tratarán para atender tus consultas y, en su caso, remitirte información relacionada con nuestros servicios.</p>

  <h2>3. Legitimación</h2>
  <p>La base legal es el consentimiento del interesado, que queda registrado con su fecha y hora al enviar el formulario, y/o la ejecución de una relación contractual o precontractual.</p>

  <h2>4. Conservación</h2>
  <p>Los datos se conservarán mientras exista una relación de interés mutuo o hasta que el interesado solicite su supresión.</p>

  <h2>5. Destinatarios</h2>
  <p>No se cederán datos a terceros salvo obligación legal o proveedores de servicios necesarios para la prestación (encargados del tratamiento).</p>

  <h2>6. Derechos</h2>
  <p>Puedes ejercer tus derechos de acceso, rectificación, supresión, oposición, limitación y portabilidad escribiendo a info@scrapenvases.com. Asimismo, tienes derecho a presentar una reclamación ante la Agencia Española de Protección de Datos (www.aepd.es).</p>
